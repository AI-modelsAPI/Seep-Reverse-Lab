CONDS = ['TRUE','EQ','NE','GT','GE','LT','LE','A','AE','B','BE']

def decode(path=PATH, limit=0x400):
    pe = pefile.PE(path)
    code = pe.get_data(BC_RVA, 0x3000)
    iat = {}
    for e in pe.DIRECTORY_ENTRY_IMPORT:
        for imp in e.imports:
            if imp.name:
                iat[imp.address - 0x140000000] = f"{e.dll.decode().split('.')[0]}!{imp.name.decode()}"
    out, vip = [], 0
    while vip < limit and vip < len(code):
        op = code[vip]; ln = LEN.get(op, 1)
        raw = code[vip:vip+max(ln, 10)]
        nm = NAME.get(op, f'OP{op:02x}'); args = ''

        if ln == 3:
            args = f"r{raw[1]}, r{raw[2]}"
        elif ln == 4:
            args = f"r{raw[1]}, r{raw[2]}, w={raw[3]}"
        elif ln == 5:
            a = vip + (2 if nm == 'LEA' else 1)
            imm = d32(struct.unpack_from('<I', raw, a - vip)[0], a)
            if nm == 'CALL':
                if imm & 0x80000000:
                    rva = imm & 0x7FFFFFFF
                    args = f"*{iat.get(rva, hex(rva))}"
                else:
                    args = f"0x{imm:x}"
            elif nm == 'LEA':
                args = f"r{raw[1]}, base+0x{imm:x}"
            else:
                args = f"r{raw[1]}, 0x{imm:x}"
        elif ln == 6:
            if nm == 'LEA':
                a = vip + 2
                imm = d32(struct.unpack_from('<I', raw, 2)[0], a)
                args = f"r{raw[1]}, base+0x{imm:x}"
            else:
                cond = raw[1]; tgt = struct.unpack_from('<I', raw, 2)[0]
                args = f"{CONDS[cond] if cond < len(CONDS) else cond}, -> 0x{tgt:03x}"
        elif ln == 7:
            args = f"r{raw[1]}, r{raw[2]}, w={raw[3]}, 0x{struct.unpack_from('<H',raw,5)[0]:x}"
        elif ln == 8:
            d = struct.unpack_from('<I', raw, 4)[0]
            args = f"r{raw[1]}, r{raw[2]}, w={raw[3]}, disp=[{d if d<2**31 else d-2**32}]"
        elif ln in (9, 10):
            a = vip + 1
            imm = d64(struct.unpack_from('<Q', raw, 1)[0], a)
            args = f"r{raw[1]}, 0x{imm:016x}"
        elif ln == 2:
            args = f"r{raw[1]}" if raw[1] < 0x80 else ""
        out.append((vip, op, nm, args)); vip += ln
    return out

