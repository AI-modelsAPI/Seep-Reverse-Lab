MASK = (1 << 64) - 1
def d32(v, a): return (v ^ ((((M32 * (a & 0xFFFFFFFF)) & 0xFFFFFFFF) ^ K32) & 0xFFFFFFFF)) & 0xFFFFFFFF
def d64(v, a): return (v ^ (((M64 * a) & MASK) ^ K64)) & MASK

